/** Very small keyword search — good enough for a picker, zero dependencies. */
export function searchEmojis(term: string, limit = 40): string[] {
  const needle = term.trim().toLowerCase();
  if (!needle) return [];

  const matches = new Set<string>();
  for (const [keyword, emojis] of Object.entries(KEYWORD_INDEX)) {
    if (keyword.includes(needle)) {
      for (const emoji of emojis) matches.add(emoji);
    }
  }
  for (const category of EMOJI_CATEGORIES) {
    if (category.label.toLowerCase().includes(needle) || category.id.includes(needle)) {
      for (const emoji of category.emojis.slice(0, 24)) matches.add(emoji);
    }
  }
  return [...matches].slice(0, limit);
}
